"""Render ``metrics.json`` as markdown and keep the README's results section in sync.

The README never contains hand-typed numbers: everything between the ``RESULTS`` markers
is regenerated from the metrics of the latest run.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Mapping

START_MARKER = "<!-- RESULTS:START -->"
END_MARKER = "<!-- RESULTS:END -->"

MODEL_LABELS: dict[str, str] = {
    "popularity": "Popularity (global baseline)",
    "recent_popularity": "Popularity, last 28 days (reference)",
    "als": "ALS",
    "hybrid": "Hybrid (ALS + content fallback)",
}
SEGMENT_LABELS: dict[str, str] = {
    "all": "All users",
    "established": "Established (>= 3 items)",
    "low_history": "Low history (1-2 items)",
    "new": "New (0 items)",
}


def _pct(value: float, signed: bool = False) -> str:
    return f"{value * 100:+.1f}%" if signed else f"{value * 100:.1f}%"


def _metric_row(label: str, summary: Mapping[str, Any], k: int) -> str:
    diversity = "n/a" if summary.get("diversity") is None else f"{summary['diversity']:.3f}"
    return (f"| {label} | {summary[f'recall@{k}']:.4f} | {summary[f'precision@{k}']:.4f} | "
            f"{summary[f'ndcg@{k}']:.4f} | {diversity} | {_pct(summary['coverage'])} |")


def render_results(metrics: Mapping[str, Any]) -> str:
    """Build the markdown results section from a metrics dictionary."""
    k = metrics["protocol"]["k"]
    data, split = metrics["data"], metrics["split"]
    segments, headline = metrics["user_segments"]["test"], metrics["headline"]
    test = metrics["test_metrics"]
    header = (f"| Model | Recall@{k} | Precision@{k} | NDCG@{k} | Diversity | Coverage |\n"
              "|---|---|---|---|---|---|")
    lines: list[str] = []

    source = ("UCI Online Retail II" if data["source"] == "uci_online_retail_ii"
              else "**synthetic transactions** (the UCI download failed)")
    lines += [
        f"_Generated by `python -m src.run_all` from `results/metrics.json`. Data: {source}._",
        "",
        f"**Data.** {data['raw_rows']:,} raw invoice lines -> {data['clean_rows']:,} clean "
        f"purchase lines -> {data['interactions']:,} user-item interactions "
        f"({data['customers']:,} customers, {data['products']:,} products).",
        "",
        f"**Split.** Train+validation `{split['bounds']['train_start'][:10]}` to "
        f"`{split['bounds']['test_start'][:10]}` (exclusive), test `{split['bounds']['test_start'][:10]}` "
        f"to `{split['bounds']['test_end'][:10]}` (exclusive). "
        f"{segments['n_users']:,} test users have at least one new item in the test window.",
        "",
        f"### Test set, all {segments['n_users']:,} users",
        "",
        header,
    ]
    lines += [_metric_row(MODEL_LABELS[m], test[m]["all"], k) for m in MODEL_LABELS]
    low, high = headline["recall_lift_ci95"]
    lines += [
        "",
        f"**Headline.** Hybrid recall@{k} is {headline['hybrid_recall']:.4f} against "
        f"{headline['popularity_recall']:.4f} for the global popularity baseline: a relative lift of "
        f"**{_pct(headline['recall_lift_vs_popularity'], signed=True)}** "
        f"(95% paired-bootstrap interval {_pct(low, signed=True)} to {_pct(high, signed=True)}). "
        f"Against the stronger last-28-days popularity reference the lift is "
        f"{_pct(headline['recall_lift_vs_recent_popularity'], signed=True)}.",
        "",
        "### User segments",
        "",
        f"| Segment (training history) | Test users | Share | Served by |\n|---|---|---|---|",
    ]
    served = {"established": "ALS", "low_history": "content-based fallback",
              "new": "popularity (no profile possible)"}
    for name, by in served.items():
        lines.append(f"| {SEGMENT_LABELS[name]} | {segments[name]['n_users']:,} | "
                     f"{_pct(segments[name]['share'])} | {by} |")
    train = metrics["user_segments"]["train_customers"]
    lines += [
        "",
        f"So **{_pct(segments['below_threshold_share'])}** of evaluated test users are below the "
        f"3-interaction threshold, almost all of them brand-new customers. Among the "
        f"{train['n_users']:,} customers in the training data, {train['below_threshold']:,} "
        f"({_pct(train['below_threshold_share'])}) have fewer than 3 distinct items.",
        "",
        f"### Recall@{k} by segment",
        "",
        "| Model | " + " | ".join(SEGMENT_LABELS[s] for s in SEGMENT_LABELS) + " |",
        "|---|" + "---|" * len(SEGMENT_LABELS),
    ]
    for model in MODEL_LABELS:
        cells = [f"{test[model][s][f'recall@{k}']:.4f}" if test[model][s]["n_users"] else "n/a"
                 for s in SEGMENT_LABELS]
        lines.append(f"| {MODEL_LABELS[model]} | " + " | ".join(cells) + " |")
    lines += [
        "",
        f"![Recall@{k} by model and user segment](results/recall_at_{k}_by_segment.png)",
        "",
        "### Simulated cold-start (test set)",
        "",
        f"Only {segments['low_history']['n_users']} real test users have 1-2 training items, too "
        "few to judge the content fallback. To measure it properly, each established test user's "
        "history is hidden except for their 1 or 2 most recent items, and each model must "
        "recommend from that alone (ALS re-solves the user vector from the visible items).",
        "",
    ]
    for n_visible, models in metrics["simulated_cold_start"].items():
        n_users = next(iter(models.values()))["n_users"]
        lines += [f"**{n_visible} visible item{'s' if n_visible != '1' else ''}** "
                  f"({n_users:,} users)", "", header]
        labels = {"popularity": "Popularity", "content": "Content-based fallback",
                  "als_fold_in": "ALS (fold-in)"}
        lines += [_metric_row(labels[m], models[m], k) for m in labels]
        lines.append("")
    tuning = metrics["tuning"]
    best = tuning["als_best_params"]
    lines += [
        "### Tuned hyperparameters (chosen on validation)",
        "",
        f"- ALS ({tuning['n_trials']} Optuna trials): factors={best['factors']}, "
        f"regularization={best['regularization']:.4g}, iterations={best['iterations']}, "
        f"alpha={best['alpha']:.4g}, weighting={best['weighting']}",
        f"- Content fallback (grid): category_weight={tuning['content_best_params']['category_weight']}, "
        f"popularity_weight={tuning['content_best_params']['popularity_weight']}",
        f"- Objective: {tuning['accuracy_weight']} x relative precision@{k} + "
        f"{round(1 - tuning['accuracy_weight'], 2)} x relative diversity "
        f"(best value {tuning['als_best_objective']:.3f}; popularity scores 1.000 by definition)",
    ]
    return "\n".join(lines)


def update_readme(readme_path: Path, results_markdown: str) -> bool:
    """Replace the block between the results markers; returns False if they are missing."""
    if not readme_path.exists():
        return False
    text = readme_path.read_text(encoding="utf-8")
    if START_MARKER not in text or END_MARKER not in text:
        return False
    head, rest = text.split(START_MARKER, 1)
    _, tail = rest.split(END_MARKER, 1)
    readme_path.write_text(f"{head}{START_MARKER}\n{results_markdown}\n{END_MARKER}{tail}",
                           encoding="utf-8")
    return True
